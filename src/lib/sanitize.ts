import sanitizeHtml from "sanitize-html";

export function cleanHtml(html: string): string {
  return sanitizeHtml(html, {
    allowedTags: [
      "h2",
      "h3",
      "h4",
      "p",
      "br",
      "strong",
      "em",
      "b",
      "i",
      "ul",
      "ol",
      "li",
      "blockquote",
      "cite",
      "a",
      "img",
      "figure",
      "figcaption",
      "span",
      "div",
      "section",
      "article",
      "table",
      "thead",
      "tbody",
      "tr",
      "th",
      "td",
      "dl",
      "dt",
      "dd",
    ],
    allowedAttributes: {
      a: ["href", "target", "rel"],
      img: ["src", "alt", "width", "height", "loading", "decoding"],
      span: ["class"],
      blockquote: ["class"],
      div: ["class", "data-block", "data-mw-slot"],
      section: ["class", "data-facts", "data-block"],
      article: ["class", "data-animal-id", "data-project-id", "data-block"],
      figure: ["class"],
      table: ["class"],
      th: ["scope", "class"],
      td: ["class"],
      p: ["class"],
      ul: ["class"],
      ol: ["class"],
      li: ["class"],
      dl: ["class"],
      dt: ["class"],
      dd: ["class"],
      h2: ["class"],
      h3: ["class"],
      h4: ["class"],
    },
    allowedSchemes: ["http", "https", "mailto"],
  });
}

